package com.proximtecproduct.tutor_tuteee.tutor;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.proximtecproduct.tutor_tuteee.user.User;
import com.proximtecproduct.tutor_tuteee.user.UserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.mockito.ArgumentCaptor;

import java.util.Collections;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.Mockito.*;

/**
 * Unit tests for the TutorProfileService class.
 * This class uses Mockito to mock dependencies and verify business logic.
 */
@ExtendWith(MockitoExtension.class)
class TutorProfileServiceTest {

    @InjectMocks
    private TutorProfileService tutorProfileService;

    @Mock
    private TutorProfileRepository repo;
    @Mock
    private UserRepository users;
    @Mock
    private ObjectMapper om;

    // Test data
    private User testUser;
    private TutorProfile testProfile;
    private TutorProfileDto testDto;
    private TutorSearchCriteria searchCriteria;

    @BeforeEach
    void setUp() throws Exception {
        testUser = new User();
        testUser.setId(1L);
        testUser.setEmail("test@example.com");

        testProfile = new TutorProfile();
        testProfile.setId(1L);
        testProfile.setUser(testUser);
        testProfile.setBio("Original bio");

        testDto = new TutorProfileDto();
        testDto.setBio("Updated bio");
        testDto.setHourlyRateCents(5000);
        testDto.setCity("Johannesburg");
        testDto.setCountry("South Africa");
        testDto.setSubjects(List.of("Math", "Science"));
        testDto.setAvailability(Collections.emptyList());
        
        searchCriteria = new TutorSearchCriteria();
        searchCriteria.setSubject("Math");
    }

    /**
     * Test case for upserting a tutor profile that already exists.
     */
    @Test
    void upsert_withExistingProfile_updatesProfile() throws Exception {
        // Given
        when(users.findByEmail(testUser.getEmail())).thenReturn(Optional.of(testUser));
        when(repo.findByUserEmail(testUser.getEmail())).thenReturn(Optional.of(testProfile));
        when(om.writeValueAsString(any())).thenReturn("[]");
        when(repo.save(any(TutorProfile.class))).thenAnswer(invocation -> invocation.getArgument(0));

        // When
        TutorProfile updatedProfile = tutorProfileService.upsert(testUser.getEmail(), testDto);

        // Then
        assertNotNull(updatedProfile);
        assertEquals(testProfile.getId(), updatedProfile.getId());
        assertEquals("Updated bio", updatedProfile.getBio());
        assertEquals(5000, updatedProfile.getHourlyRateCents());
        verify(repo).save(any(TutorProfile.class));
    }

    /**
     * Test case for upserting a new tutor profile.
     */
    @Test
    void upsert_withNewProfile_createsNewProfile() throws Exception {
        // Given
        when(users.findByEmail(testUser.getEmail())).thenReturn(Optional.of(testUser));
        when(repo.findByUserEmail(testUser.getEmail())).thenReturn(Optional.empty());
        when(om.writeValueAsString(any())).thenReturn("[]");
        when(repo.save(any(TutorProfile.class))).thenAnswer(invocation -> {
            TutorProfile newProfile = invocation.getArgument(0);
            newProfile.setId(2L); // Simulate ID generation
            return newProfile;
        });
// ... (Lines 9-10 remain the same)
// When
TutorProfile newProfile = tutorProfileService.upsert(testUser.getEmail(), testDto);

// Then
assertNotNull(newProfile);
// Change assertNull to assert that the ID was generated by the mock
assertEquals(2L, newProfile.getId()); // FIX: The returned object should have an ID
assertEquals("Updated bio", newProfile.getBio());
// ...
    }

    /**
     * Test case for upserting a profile for a user that does not exist.
     */
    @Test
    void upsert_withNonexistentUser_throwsException() {
        // Given
        when(users.findByEmail(testUser.getEmail())).thenReturn(Optional.empty());

        // When / Then
        assertThrows(IllegalArgumentException.class, () -> tutorProfileService.upsert(testUser.getEmail(), testDto));
        verify(repo, never()).save(any(TutorProfile.class));
    }

    /**
     * Test case for upserting with invalid JSON data.
     */
    @Test
    void upsert_withInvalidJson_throwsException() throws Exception {
        // Given
        when(users.findByEmail(testUser.getEmail())).thenReturn(Optional.of(testUser));
        when(repo.findByUserEmail(testUser.getEmail())).thenReturn(Optional.of(testProfile));
        when(om.writeValueAsString(any())).thenThrow(new RuntimeException("Mock JSON error"));

        // When / Then
        assertThrows(IllegalArgumentException.class, () -> tutorProfileService.upsert(testUser.getEmail(), testDto));
        verify(repo, never()).save(any(TutorProfile.class));
    }

    /**
     * Test case for a successful search of tutors.
     */
    @Test
    void search_withValidCriteria_returnsProfiles() {
        // Given
        List<TutorProfile> mockResults = List.of(testProfile);
        when(repo.search(searchCriteria.getSubject(), searchCriteria.getCity(), searchCriteria.getMinRate(), searchCriteria.getMaxRate()))
                .thenReturn(mockResults);

        // When
        List<TutorProfile> results = tutorProfileService.search(searchCriteria);

        // Then
        assertFalse(results.isEmpty());
        assertEquals(1, results.size());
        assertEquals(testProfile, results.get(0));
        verify(repo).search(searchCriteria.getSubject(), searchCriteria.getCity(), searchCriteria.getMinRate(), searchCriteria.getMaxRate());
    }

    /**
     * Test case for retrieving a tutor profile by an existing ID.
     */
    @Test
    void getById_withExistingTutor_returnsTutor() {
        // Given
        when(repo.findById(testProfile.getId())).thenReturn(Optional.of(testProfile));

        // When
        TutorProfile result = tutorProfileService.getById(testProfile.getId());

        // Then
        assertNotNull(result);
        assertEquals(testProfile.getId(), result.getId());
    }

    /**
     * Test case for retrieving a tutor profile with a non-existent ID.
     */
    @Test
    void getById_withNonexistentTutor_throwsException() {
        // Given
        when(repo.findById(anyLong())).thenReturn(Optional.empty());

        // When / Then
        assertThrows(IllegalArgumentException.class, () -> tutorProfileService.getById(999L));
    }
}